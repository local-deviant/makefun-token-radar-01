// Token radar entrypoint: reads the sealed snapshot, fits the model, writes
// the board, the dashboard data, and the dossier. Node 22 stdlib only.
// Usage: MAKEFUN_OUTPUT_DIR=out node main.ts --input input/snapshot.json
// Defaults: input /input/snapshot.json, output $MAKEFUN_OUTPUT_DIR or /output.

import { cpSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDossier } from './vendor/makefun-board.ts';
import {
  loadSnapshot,
  buildBoard,
  selectComps,
  formatUsd,
  bandLow,
  type BoardRow,
} from './lib/model.ts';
import { validateAll } from './lib/validate.ts';

const repoRoot = dirname(fileURLToPath(import.meta.url));

function arg(name: string, fallback: string): string {
  const i = process.argv.indexOf(name);
  return i >= 0 && i + 1 < process.argv.length ? process.argv[i + 1] : fallback;
}

const inputPath = arg('--input', '/input/snapshot.json');
const outDir = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';

const snap = loadSnapshot(inputPath);
const board = buildBoard(snap);
const validation = validateAll(snap);

mkdirSync(join(outDir, 'dashboard'), { recursive: true });
mkdirSync(join(outDir, 'screenshots'), { recursive: true });

// ---- board.json: the ranked board with farm plans
const boardJson = {
  as_of: snap.as_of,
  model: 'OLS ln(mcap) on ln(TVL) and ln(age), category offsets shrunk by 8, multiple clamped [0.08, 1.20], growth 1 + clamp(7d, -60%, +120%) x 0.3, no pre-token discount',
  band: Number(board.band.toFixed(2)),
  rows: board.rows.map((r: BoardRow) => ({
    slug: r.slug,
    name: r.name,
    rank: r.rank,
    implied_value_usd: r.implied_value_usd,
    verdict: r.verdict,
    category: r.category,
    tvl_usd: r.tvl_usd,
    change_7d: r.change_7d,
    age_days: r.age_days,
    multiple: Number(r.multiple.toFixed(4)),
    growth: Number(r.growth.toFixed(4)),
    on_watchlist: r.on_watchlist,
    farm_steps: r.farm_steps,
  })),
};
writeFileSync(join(outDir, 'board.json'), `${JSON.stringify(boardJson, null, 2)}\n`, 'utf8');

// ---- dashboard/data.js: compact board data for the page (steps are generated
// client-side by app.js from the same templates, so this stays small)
const dataRows = board.rows.map((r: BoardRow) => [
  r.slug,
  r.name,
  r.implied_value_usd,
  r.verdict === 'FARM' ? 0 : r.verdict === 'THIN' ? 1 : 2,
  r.category ?? '',
  r.tvl_usd,
  r.change_7d,
  r.age_days,
  Number(r.multiple.toFixed(4)),
  Number(r.growth.toFixed(4)),
  r.on_watchlist ? 1 : 0,
  r.chains[0] ?? '',
  bandLow(r.implied_value_usd, board.band),
]);
// The comparables whose token already trades, shown so the board's separation is visible.
const liveTop = selectComps(snap.protocols)
  .sort((a, b) => (b.mcap_usd as number) - (a.mcap_usd as number))
  .slice(0, 8)
  .map((p) => [p.name, `${formatUsd(p.mcap_usd as number)} mcap`, p.symbol ?? '']);
const dataJs = [
  '// Generated by main.ts from the sealed snapshot; do not edit by hand.',
  `window.BOARD = ${JSON.stringify(dataRows)};`,
  `window.LIVE = ${JSON.stringify(liveTop)};`,
  `window.META = ${JSON.stringify({
    as_of: snap.as_of,
    band: Number(board.band.toFixed(2)),
    beta: board.curve.beta.map((b) => Number(b.toFixed(4))),
    n_comps: board.curve.nComps,
    loo_median: validation.loo.median,
    loo_geo: validation.loo.geo,
    loo_spearman: validation.loo.spearman,
    ts_median: validation.time_split.median,
    wf_median: validation.walk_forward.pooled_median,
    wf_folds: validation.walk_forward.folds,
    base_median_multiple: validation.baselines.median_multiple_loo_median,
    base_tvl_only: validation.baselines.tvl_only_loo_median,
    bootstrap_top10: validation.bootstrap.top10_kept_mean,
    bootstrap_rank1_pct: validation.bootstrap.rank1_kept_pct,
    counts: {
      FARM: board.rows.filter((r) => r.verdict === 'FARM').length,
      THIN: board.rows.filter((r) => r.verdict === 'THIN').length,
      SKIP: board.rows.filter((r) => r.verdict === 'SKIP').length,
    },
  })};`,
  '',
].join('\n');
writeFileSync(join(outDir, 'dashboard', 'data.js'), dataJs, 'utf8');

// ---- dashboard sources and screenshots, copied as-is
for (const f of ['index.html', 'app.css', 'app.js']) {
  cpSync(join(repoRoot, 'dashboard', f), join(outDir, 'dashboard', f));
}
cpSync(join(repoRoot, 'screenshots'), join(outDir, 'screenshots'), { recursive: true });

// ---- dossier.json: byte for byte what buildDossier writes
const dossier = buildDossier(outDir, { text_max_bytes: 65536 });
writeFileSync(join(outDir, 'dossier.json'), dossier);

const verdicts = { FARM: 0, THIN: 0, SKIP: 0 };
for (const r of board.rows) verdicts[r.verdict]++;
console.log(`board: ${board.rows.length} rows, band x${board.band.toFixed(2)}, verdicts ${JSON.stringify(verdicts)}`);
console.log(`top: ${board.rows[0].name} ${formatUsd(board.rows[0].implied_value_usd)}`);
console.log(`dossier: ${dossier.length} bytes -> ${join(outDir, 'dossier.json')}`);
